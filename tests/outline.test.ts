      '\t\tconst val LIMIT = 10',
      '\t\tfun create(): Store = TODO()',
      '\t}',
      '',
      '\t@Transactional',
      '\toverride suspend fun save(x: String): Int {',
      '\t\tval y = 2',
      '\t\tfun inner() = 3',
      '\t\treturn db.put(x)',
      '\t}',
      '',
      '\tfun <T> List<T>.firstOr(d: T): T = firstOrNull() ?: d',
